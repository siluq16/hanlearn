export function getUnitMeta(unitIdOrNum: string | number): UnitMetadata {
  let found: UnitMetadata | undefined;
  if (typeof unitIdOrNum === "number") {
    found = UNIFIED_UNITS.find((u) => u.unitNumber === unitIdOrNum);
  } else {
    const cleanId = String(unitIdOrNum);
    found = UNIFIED_UNITS.find(
      (u) =>
        u.id === cleanId ||
        u.id === `u-hsk1-0${cleanId}` ||
        String(u.unitNumber) === cleanId
    );
  }
  return found || UNIFIED_UNITS[0];
}

export function getLessonMeta(slug: string): LessonMetadata {
  if (UNIFIED_LESSONS[slug]) {
    return UNIFIED_LESSONS[slug];
  }
  // Fallback for custom or checkpoint slugs
  return {
    slug,
    lessonNumber: 1,
    unitId: "u-hsk1-01",
    unitNumber: 1,
    shortTitle: slug,
    fullTitle: slug,
    objectiveVi: "",
    estimatedMinutes: 25,
  };
}

export function getPracticeSetMeta(setId: string): PracticeSetMetadata {
  return (
    UNIFIED_PRACTICE_SETS[setId] || {
      id: setId,
      unitId: "u-hsk1-01",
      unitNumber: 1,
      skill: "vocabulary",
      setNumber: 1,
      setCode: "Bộ bài",
      shortTitle: setId,
      fullTitle: setId,
      difficulty: "easy",
      description: "",
    }
  );
}

export function getExamMeta(idOrSlug: string): ExamMetadata | undefined {
  return (
    UNIFIED_EXAMS[idOrSlug] ||
    Object.values(UNIFIED_EXAMS).find(
      (e) => String(e.unitNumber) === idOrSlug || e.id === `hsk1-unit-test-0${idOrSlug}`
    )
  );
}
